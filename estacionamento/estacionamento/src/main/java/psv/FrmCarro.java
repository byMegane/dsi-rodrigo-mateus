    private void btnPesquisarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPesquisarActionPerformed
        Connection con = null;

        try {
            con = Conexao.abrirConexao();

            if (con == null) {
                lblMensagem.setText("Erro ao conectar ao banco!");
                return;
            }

            CarroDAO dao = new CarroDAO(con);
            List<CarroBean> carros = dao.listarTodos();

            if (carros == null) {
                lblMensagem.setText("Erro ao consultar veículos!");
                return;
            }

            DefaultTableModel modelo =
                    (DefaultTableModel) tblConsulta.getModel();

            modelo.setRowCount(0);

            for (CarroBean carro : carros) {
                modelo.addRow(new Object[]{
                    carro.getPlaca(),
                    carro.getCor(),
                    carro.getDescricao()
                });
            }

            lblMensagem.setText(
                    carros.size() + " veículo(s) encontrado(s)."
            );

        } catch (Exception e) {
            lblMensagem.setText("Erro ao pesquisar veículos!");
            e.printStackTrace();

        } finally {
            Conexao.fecharConexao(con);
        }// TODO add your handling code here:
    }//GEN-LAST:event_btnPesquisarActionPerformed

