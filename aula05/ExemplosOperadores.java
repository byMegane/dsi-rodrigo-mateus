package aula05;

public class ExemplosOperadores {
    public static void main(String[] args) {
        int x = 100;
        int y = 2;

        System.out.println(x + y);
        System.out.println(x - y);
        System.out.println(x * y);
        System.out.println(x / y);
        System.out.println(x % y);

        ++x;
        System.out.println(x);
        --x;
        System.out.println(x);

        int a = 100;
        int b = 67;
        System.out.println(a / b);
          
        double c = 100.0d;
        double d = 67.0d;
        System.out.println(c / d);
    }
}
